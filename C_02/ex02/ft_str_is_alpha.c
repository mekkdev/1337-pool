int	ft_str_is_alpha(char *str)
{
	int	i;
	int	c;

	i = 0;
	c = 0;
	if (str[0] == '\0')
		return (1);
	while (str[i] != '\0')
	{
		if (str[i] >= 'A' && str[i] <= 'Z')
			c++;
		else if (str[i] >= 'a' && str[i] <= 'z')
			c++;
		i++;
	}
	if (c == i)
		return (1);
	else
		return (0);
}
